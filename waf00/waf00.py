def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog=TOOL_NAME,
        description="Advanced multi-layer WAF/Firewall detection tool",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python waf00.py https://example.com
  python waf00.py example.com -v
  python waf00.py https://target.com --passive-only
  python waf00.py https://target.com --report results.json
  python waf00.py https://target.com --proxy http://127.0.0.1:8080
  python waf00.py https://target.com --timeout 15 -v --report out.json
        """,
    )
    p.add_argument("target", help="Target URL or domain (e.g. https://example.com or example.com)")
    p.add_argument("-v", "--verbose", action="store_true",
                   help="Show all detection signals in the report")
    p.add_argument("--passive-only", action="store_true",
                   help="Only run passive fingerprinting (no active probes sent)")
    p.add_argument("--report", metavar="FILE",
                   help="Save full JSON report to this file path")
    p.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT,
                   help=f"HTTP request timeout in seconds (default: {DEFAULT_TIMEOUT})")
    p.add_argument("--proxy", metavar="URL",
                   help="HTTP/HTTPS proxy URL (e.g. http://127.0.0.1:8080)")
    p.add_argument("--no-ssl-verify", action="store_true",
                   help="Disable SSL certificate verification")
    p.add_argument("--version", action="version", version=f"%(prog)s {VERSION}")
    return p


def main():
    print_banner()
    parser = build_parser()
    args   = parser.parse_args()

    _print_info(f"Target  : {args.target}")
    if args.passive_only:
        _print_yellow("Mode    : Passive only (no active probes)")
    else:
        _print_info(f"Mode    : Full scan ({len(PROBE_PAYLOADS)} active probes + passive + behavioral)")
    if args.proxy:
        _print_info(f"Proxy   : {args.proxy}")
    print()

    scanner = WAFScanner(
        target=args.target,
        timeout=args.timeout,
        verify_ssl=not args.no_ssl_verify,
        proxy=args.proxy,
        skip_active=args.passive_only,
        verbose=args.verbose,
    )

    try:
        report = scanner.scan()
    except KeyboardInterrupt:
        print()
        _print_error("Scan interrupted by user.")
        sys.exit(1)

    print_report(report, verbose=args.verbose)

    # Save JSON report
    if args.report:
        try:
            report_dict = asdict(report)
            with open(args.report, "w", encoding="utf-8") as f:
                json.dump(report_dict, f, indent=2)
            _print_ok(f"JSON report saved to: {args.report}")
        except Exception as e:
            _print_error(f"Failed to save report: {e}")

    # Exit code: 1 if WAF detected, 0 if not (useful in scripts/CI)
    sys.exit(1 if report.waf_detected else 0)


if __name__ == "__main__":
    main()
