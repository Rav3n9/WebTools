# MAIN SCANNER ORCHESTRATOR
# ─────────────────────────────────────────────────────────────────────────────
class WAFScanner:
    """
    Orchestrates all four detection layers and produces a DetectionReport.
    """

    def __init__(self, target: str, timeout: int = DEFAULT_TIMEOUT,
                 verify_ssl: bool = False, proxy: Optional[str] = None,
                 skip_active: bool = False, verbose: bool = False):
        self.target      = self._normalise_url(target)
        self.skip_active = skip_active
        self.verbose     = verbose
        self.client      = HTTPClient(timeout=timeout, verify_ssl=verify_ssl,
                                       proxy=proxy, delay=not skip_active)
        self.passive     = PassiveDetector()
        self.behavioral  = BehavioralAnalyzer()
        self.scorer      = ConfidenceEngine()

    @staticmethod
    def _normalise_url(url: str) -> str:
        url = url.strip()
        if not url.startswith(("http://", "https://")):
            url = "https://" + url
        return url.rstrip("/")

    def scan(self) -> DetectionReport:
        from datetime import datetime, timezone
        report = DetectionReport(
            target=self.target,
            scan_time=datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
            waf_detected=False,
        )

        all_signals: list = []

        # ── Baseline request (normal GET /) ───────────────────────────────────
        _print_info(f"[1/4] Sending baseline request to {self.target} ...")
        baseline = self.client.get(self.target)

        if baseline.error and baseline.status_code == 0:
            _print_error(f"Baseline request failed: {baseline.error}")
            report.verdict = f"Scan failed: {baseline.error}"
            return report

        report.baseline = {
            "status_code": baseline.status_code,
            "response_time": baseline.response_time,
            "body_length": len(baseline.body_snippet),
            "server": baseline.headers.get("Server", baseline.headers.get("server", "N/A")),
        }
        report.raw_headers = baseline.headers
        _print_ok(f"   Baseline: HTTP {baseline.status_code}, "
                  f"{len(baseline.body_snippet)}B body, "
                  f"{baseline.response_time}s")

        # ── Layer 1: Passive fingerprinting ───────────────────────────────────
        _print_info("[2/4] Running passive fingerprinting ...")
        passive_signals = self.passive.analyse(baseline)
        all_signals.extend(passive_signals)
        _print_ok(f"   Passive signals found: {len(passive_signals)}")

        # ── Layer 2: Active probing ────────────────────────────────────────────
        probe_results = []
        if self.skip_active:
            _print_dim("[3/4] Active probing SKIPPED (--passive-only flag set)")
        else:
            _print_info(f"[3/4] Running {len(PROBE_PAYLOADS)} active probes "
                        f"(rate-limited, {MIN_DELAY}-{MAX_DELAY}s delays) ...")
            active_detector = ActiveDetector(self.client, self.target, self.verbose)
            active_signals, probe_results = active_detector.run_probes(baseline)
            all_signals.extend(active_signals)
            _print_ok(f"   Active signals found: {len(active_signals)}")

        # ── Layer 3: Behavioral analysis ──────────────────────────────────────
        _print_info("[4/4] Running behavioral analysis ...")
        if probe_results:
            behavioral_signals = self.behavioral.analyse(baseline, probe_results)
            all_signals.extend(behavioral_signals)
            _print_ok(f"   Behavioral signals found: {len(behavioral_signals)}")

            # Probe summary stats
            valid_pr = [r for r in probe_results if not r.error and r.status_code > 0]
            if valid_pr:
                report.probe_summary = {
                    "total_probes": len(PROBE_PAYLOADS),
                    "successful_probes": len(valid_pr),
                    "blocked_probes": sum(1 for r in valid_pr if r.status_code in BLOCK_STATUS_CODES),
                    "avg_response_time": round(
                        sum(r.response_time for r in valid_pr) / len(valid_pr), 3),
                    "status_codes_seen": sorted(set(r.status_code for r in valid_pr)),
                }
        else:
            _print_dim("   Behavioral analysis skipped (no probe data)")

        # ── Score and finalise ─────────────────────────────────────────────────
        score, waf_names, verdict = self.scorer.compute(all_signals)
        report.confidence   = score
        report.waf_names    = waf_names
        report.verdict      = verdict
        report.waf_detected = score > 20
        report.signals      = [asdict(s) for s in all_signals]
        report.recommendations = self._make_recommendations(score, waf_names, all_signals)

        return report

    def _make_recommendations(self, score: int, waf_names: list, signals: list) -> list:
        recs = []
        if score > 20:
            recs.append("A WAF/firewall is likely protecting this target. Consider evasion techniques "
                        "or out-of-band testing before active exploitation attempts.")
        if any(s.get("signal_type") == "timing" for s in [asdict(x) for x in signals]):
            recs.append("Response time spikes detected — the WAF may be performing deep packet inspection. "
                        "Slow down attack timing significantly.")
        if "Cloudflare" in waf_names:
            recs.append("Cloudflare detected: look for origin IP leaks via DNS history, "
                        "Shodan, or Certificate Transparency logs to bypass the CDN layer.")
        if "AWS WAF / CloudFront" in waf_names:
            recs.append("AWS WAF detected: check for misconfigured S3 buckets or API Gateway "
                        "endpoints that may bypass WAF rules.")
        if score <= 20:
            recs.append("No WAF detected. The target may be directly accessible, "
                        "or using a custom/unknown firewall solution.")
        return recs


