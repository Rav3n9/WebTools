# OUTPUT / DISPLAY HELPERS
# ─────────────────────────────────────────────────────────────────────────────
def _c(text: str, code: str) -> str:
    """ANSI colour wrapper — degrades gracefully on Windows without colour support."""
    if sys.platform == "win32":
        try:
            import ctypes
            ctypes.windll.kernel32.SetConsoleMode(
                ctypes.windll.kernel32.GetStdHandle(-11), 7)
        except Exception:
            return text
    return f"\033[{code}m{text}\033[0m"

def _print_info(msg):  print(_c(f"[*] {msg}", "94"))
def _print_ok(msg):    print(_c(f"[+] {msg}", "92"))
def _print_yellow(msg):print(_c(f"[!] {msg}", "93"))
def _print_error(msg): print(_c(f"[✗] {msg}", "91"))
def _print_dim(msg):   print(_c(f"    {msg}", "90"))


def print_banner():
    banner = """
  +--------------------------------------------------+
  |   waf00 v{version:<10}                           |
  |   Advanced WAF / Firewall Detection Tool         |
  |   4-layer: Passive | Active | Behavioral | Score |
  +--------------------------------------------------+
""".format(version=VERSION)
    print(_c(banner, "96"))


def print_report(report: DetectionReport, verbose: bool = False):
    print()
    print(_c("=" * 60, "90"))
    print(_c("  DETECTION REPORT", "1"))
    print(_c("=" * 60, "90"))
    print(f"  Target     : {report.target}")
    print(f"  Scan time  : {report.scan_time}")
    print()

    # Confidence bar
    bar_len  = 40
    filled   = int(report.confidence / 100 * bar_len)
    bar      = "#" * filled + "-" * (bar_len - filled)
    if report.confidence >= 66:
        bar_color = "91"   # red
    elif report.confidence >= 41:
        bar_color = "93"   # yellow
    else:
        bar_color = "92"   # green
    print(f"  Confidence : {_c(bar, bar_color)} {report.confidence}%")
    print()

    if report.waf_detected:
        if report.waf_names:
            print(_c(f"  [!] WAF/Firewall DETECTED", "91"))
            print(f"  Identified : {', '.join(report.waf_names)}")
        else:
            print(_c(f"  [!] WAF/Firewall DETECTED (vendor unknown)", "93"))
    else:
        print(_c("  [OK] No WAF detected", "92"))

    print(f"  Verdict    : {report.verdict}")
    print()

    # Baseline info
    if report.baseline:
        b = report.baseline
        print(_c("  -- Baseline ------------------------------------------", "90"))
        print(f"  Status     : HTTP {b.get('status_code')}")
        print(f"  Server     : {b.get('server')}")
        print(f"  Body size  : {b.get('body_length')}B")
        print(f"  Resp time  : {b.get('response_time')}s")
        print()

    # Probe summary
    if report.probe_summary:
        ps = report.probe_summary
        print(_c("  -- Active Probe Summary ------------------------------", "90"))
        print(f"  Probes sent    : {ps.get('total_probes')}")
        print(f"  Successful     : {ps.get('successful_probes')}")
        print(f"  Blocked        : {ps.get('blocked_probes')}")
        print(f"  Avg resp time  : {ps.get('avg_response_time')}s")
        print(f"  Status codes   : {ps.get('status_codes_seen')}")
        print()

    # Signals
    if verbose and report.signals:
        print(_c("  -- Detection Signals ---------------------------------", "90"))
        for s in report.signals:
            layer_color = {"passive": "94", "active": "93", "behavioral": "95"}.get(s["layer"], "97")
            waf_tag = f"[{s['matched_waf']}]" if s["matched_waf"] else "[generic]"
            layer_tag = "[{}]".format(s["layer"])
            print(f"  {_c(layer_tag, layer_color)} "
                  f"{_c(waf_tag, '96')} "
                  f"+{s['confidence_contribution']}pt -- {s['detail']}")
        print()

    # Recommendations
    if report.recommendations:
        print(_c("  -- Recommendations -----------------------------------", "90"))
        for i, rec in enumerate(report.recommendations, 1):
            print(f"  {i}. {rec}")
        print()

    print(_c("=" * 60, "90"))
    print()


