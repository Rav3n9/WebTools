# DATA CLASSES
# ─────────────────────────────────────────────────────────────────────────────
@dataclass
class ProbeResult:
    """Stores result of a single HTTP probe."""
    url: str
    method: str
    status_code: int
    response_time: float          # seconds
    headers: dict
    body_snippet: str             # first 2000 chars of body
    cookies: dict
    error: Optional[str] = None

@dataclass
class DetectionSignal:
    """A single detection signal with its source and weight."""
    layer: str                    # passive | active | behavioral
    signal_type: str              # header | cookie | body | status | timing | delta
    detail: str                   # human-readable description
    matched_waf: Optional[str]    # specific WAF name if matched, else None
    confidence_contribution: int  # 0-100 points added to overall score

@dataclass
class DetectionReport:
    """Full detection report for a target."""
    target: str
    scan_time: str
    waf_detected: bool
    waf_names: list = field(default_factory=list)
    confidence: int = 0           # 0-100
    verdict: str = ""
    signals: list = field(default_factory=list)
    baseline: dict = field(default_factory=dict)
    probe_summary: dict = field(default_factory=dict)
    recommendations: list = field(default_factory=list)
    raw_headers: dict = field(default_factory=dict)


# ─────────────────────────────────────────────────────────────────────────────
# HTTP CLIENT
# ─────────────────────────────────────────────────────────────────────────────
class HTTPClient:
    """
    Thin requests wrapper that handles:
      - Random User-Agent rotation
      - Configurable delays between requests (IP ban avoidance)
      - Retry logic for transient errors
      - SSL verification toggle
    """

    def __init__(self, timeout: int = DEFAULT_TIMEOUT, verify_ssl: bool = False,
                 proxy: Optional[str] = None, delay: bool = True):
        self.timeout  = timeout
        self.verify   = verify_ssl
        self.proxy    = {"http": proxy, "https": proxy} if proxy else None
        self.delay    = delay
        self.session  = requests.Session()
        # Common browser headers to blend in
        self.session.headers.update({
            "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
            "Accept-Language": "en-US,en;q=0.5",
            "Accept-Encoding": "gzip, deflate",
            "Connection": "keep-alive",
            "Upgrade-Insecure-Requests": "1",
        })

    def _rotate_ua(self):
        self.session.headers["User-Agent"] = random.choice(USER_AGENTS)

    def _sleep(self):
        if self.delay:
            time.sleep(random.uniform(MIN_DELAY, MAX_DELAY))

    def get(self, url: str, extra_headers: dict = None,
            method: str = "GET") -> ProbeResult:
        self._rotate_ua()
        self._sleep()
        headers = dict(self.session.headers)
        if extra_headers:
            headers.update(extra_headers)

        start = time.time()
        for attempt in range(MAX_RETRIES + 1):
            try:
                if method == "GET":
                    resp = self.session.get(
                        url, headers=headers, timeout=self.timeout,
                        verify=self.verify, proxies=self.proxy,
                        allow_redirects=True
                    )
                else:
                    resp = self.session.request(
                        method, url, headers=headers, timeout=self.timeout,
                        verify=self.verify, proxies=self.proxy,
                        allow_redirects=True
                    )
                elapsed = time.time() - start
                body = ""
                try:
                    body = resp.text[:2000]
                except Exception:
                    pass
                cookies = {c.name: c.value for c in resp.cookies}
                return ProbeResult(
                    url=url, method=method,
                    status_code=resp.status_code,
                    response_time=round(elapsed, 3),
                    headers=dict(resp.headers),
                    body_snippet=body,
                    cookies=cookies,
                )
            except requests.exceptions.SSLError:
                # retry without SSL verify
                self.verify = False
                if attempt == MAX_RETRIES:
                    return ProbeResult(url=url, method=method, status_code=0,
                                       response_time=0, headers={},
                                       body_snippet="", cookies={},
                                       error="SSL error")
            except requests.exceptions.ConnectionError as e:
                if attempt == MAX_RETRIES:
                    return ProbeResult(url=url, method=method, status_code=0,
                                       response_time=0, headers={},
                                       body_snippet="", cookies={},
                                       error=f"Connection error: {e}")
                time.sleep(1)
            except requests.exceptions.Timeout:
                elapsed = time.time() - start
                return ProbeResult(url=url, method=method, status_code=0,
                                   response_time=round(elapsed, 3), headers={},
                                   body_snippet="", cookies={},
                                   error="Timeout")
            except Exception as e:
                return ProbeResult(url=url, method=method, status_code=0,
                                   response_time=0, headers={},
                                   body_snippet="", cookies={},
                                   error=str(e))


# ─────────────────────────────────────────────────────────────────────────────
# LAYER 1 — PASSIVE FINGERPRINTING
# ─────────────────────────────────────────────────────────────────────────────
class PassiveDetector:
    """
    Analyses a single normal response for WAF artifacts without sending
    any suspicious payloads. Zero risk of triggering blocks.

    Checks:
      - HTTP response headers against known WAF header signatures
      - Cookie names against known WAF cookie patterns
      - Response body against known WAF body patterns
    """

    def analyse(self, result: ProbeResult) -> list:
        """Returns a list of DetectionSignal."""
        signals = []
        if result.error:
            return signals

        h_lower = {k.lower(): v.lower() for k, v in result.headers.items()}
        body_lower = result.body_snippet.lower()

        for sig in WAF_SIGNATURES:
            matched_signals = []

            # ── Header matching ──────────────────────────────────────────────
            for header_name, pattern in sig.get("headers", {}).items():
                val = h_lower.get(header_name.lower(), "")
                if val and re.search(pattern, val, re.IGNORECASE):
                    matched_signals.append(
                        DetectionSignal(
                            layer="passive",
                            signal_type="header",
                            detail=f"Header '{header_name}: {result.headers.get(header_name, val)}' matches {sig['name']}",
                            matched_waf=sig["name"],
                            confidence_contribution=sig["weight"],
                        )
                    )

            # ── Cookie matching ──────────────────────────────────────────────
            for cookie_pattern in sig.get("cookies", []):
                for cookie_name in result.cookies:
                    if re.search(cookie_pattern, cookie_name, re.IGNORECASE):
                        matched_signals.append(
                            DetectionSignal(
                                layer="passive",
                                signal_type="cookie",
                                detail=f"Cookie '{cookie_name}' matches {sig['name']}",
                                matched_waf=sig["name"],
                                confidence_contribution=sig["weight"],
                            )
                        )
                        break

            # ── Body pattern matching ────────────────────────────────────────
            for body_pat in sig.get("body_patterns", []):
                if re.search(body_pat, body_lower, re.IGNORECASE):
                    matched_signals.append(
                        DetectionSignal(
                            layer="passive",
                            signal_type="body",
                            detail=f"Body matches pattern '{body_pat}' for {sig['name']}",
                            matched_waf=sig["name"],
                            confidence_contribution=sig["weight"],
                        )
                    )
                    break  # one body match per sig is enough

            signals.extend(matched_signals)

        # ── Generic security headers (vendor-neutral WAF hint) ───────────────
        security_headers = [
            "x-waf-event-info", "x-protected-by", "x-firewall-protection",
            "x-security-action", "x-iinfo", "x-rack-cache",
        ]
        for sh in security_headers:
            if sh in h_lower:
                signals.append(DetectionSignal(
                    layer="passive",
                    signal_type="header",
                    detail=f"Generic security header found: '{sh}: {h_lower[sh]}'",
                    matched_waf=None,
                    confidence_contribution=20,
                ))

        return signals


