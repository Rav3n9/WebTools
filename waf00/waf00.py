# LAYER 2 — ACTIVE PROBE DETECTION
# ─────────────────────────────────────────────────────────────────────────────
class ActiveDetector:
    """
    Sends crafted payloads one at a time with randomized delays.
    For each probe response, checks:
      - Status code against known block codes
      - Body against known WAF block messages + generic block patterns
      - Header changes compared to baseline
    Tracks aggregate probe statistics for behavioral analysis.
    """

    def __init__(self, client: HTTPClient, base_url: str, verbose: bool = False):
        self.client   = client
        self.base_url = base_url.rstrip("/")
        self.verbose  = verbose

    def run_probes(self, baseline: ProbeResult) -> tuple:
        """
        Returns (signals: list[DetectionSignal], probe_results: list[ProbeResult])
        """
        signals      = []
        probe_results = []

        for probe in PROBE_PAYLOADS:
            url = self.base_url + probe["path"]
            method = probe.get("method", "GET")
            extra_h = probe.get("extra_headers", {})

            if self.verbose:
                _print_dim(f"  → Probing [{probe['type']}] {probe['desc']} ...")

            result = self.client.get(url, extra_headers=extra_h, method=method)
            probe_results.append(result)

            if result.error:
                if self.verbose:
                    _print_dim(f"     ✗ Error: {result.error}")
                continue

            found_signals = self._analyse_probe_response(result, baseline, probe)
            signals.extend(found_signals)

            if self.verbose and found_signals:
                for s in found_signals:
                    _print_yellow(f"     ⚡ Signal [{s.signal_type}]: {s.detail}")

        return signals, probe_results

    def _analyse_probe_response(self, result: ProbeResult,
                                 baseline: ProbeResult, probe: dict) -> list:
        signals = []
        body_lower = result.body_snippet.lower()

        # ── Known WAF block body patterns ────────────────────────────────────
        for sig in WAF_SIGNATURES:
            for body_pat in sig.get("body_patterns", []):
                if re.search(body_pat, body_lower, re.IGNORECASE):
                    signals.append(DetectionSignal(
                        layer="active",
                        signal_type="body",
                        detail=f"Probe '{probe['desc']}' triggered {sig['name']} block page",
                        matched_waf=sig["name"],
                        confidence_contribution=sig["weight"],
                    ))
                    break

        # ── Generic block body patterns ──────────────────────────────────────
        for pat in GENERIC_BLOCK_PATTERNS:
            if re.search(pat, body_lower, re.IGNORECASE):
                signals.append(DetectionSignal(
                    layer="active",
                    signal_type="body",
                    detail=f"Probe '{probe['desc']}' → generic block body pattern: '{pat}'",
                    matched_waf=None,
                    confidence_contribution=25,
                ))
                break

        # ── Block status code ────────────────────────────────────────────────
        if result.status_code in BLOCK_STATUS_CODES and baseline.status_code not in BLOCK_STATUS_CODES:
            signals.append(DetectionSignal(
                layer="active",
                signal_type="status",
                detail=f"Probe '{probe['desc']}' → status {result.status_code} (baseline was {baseline.status_code})",
                matched_waf=None,
                confidence_contribution=30,
            ))

        # ── New headers appeared after probe (WAF injection) ─────────────────
        baseline_keys = {k.lower() for k in baseline.headers}
        probe_keys    = {k.lower() for k in result.headers}
        new_headers   = probe_keys - baseline_keys
        suspicious_new = [h for h in new_headers if any(
            kw in h for kw in ["waf", "firewall", "security", "block", "cf-", "x-amz", "incap", "akamai"]
        )]
        for h in suspicious_new:
            signals.append(DetectionSignal(
                layer="active",
                signal_type="header",
                detail=f"Probe '{probe['desc']}' injected new header: '{h}'",
                matched_waf=None,
                confidence_contribution=20,
            ))

        return signals


# ─────────────────────────────────────────────────────────────────────────────
# LAYER 3 — BEHAVIORAL ANALYSIS
# ─────────────────────────────────────────────────────────────────────────────
class BehavioralAnalyzer:
    """
    This is the key differentiator over WAFW00F.

    Instead of purely matching known signatures, it measures HOW the server
    BEHAVES differently when receiving suspicious vs normal requests.

    Metrics:
      - Body length delta: WAFs often return very different body sizes
      - Response time delta: WAFs add latency for inspection
      - Status code spread: WAFs produce varied codes across probes
      - Block rate: % of probes that resulted in block-like responses
      - Header volatility: headers that change across probe responses
    """

    def analyse(self, baseline: ProbeResult, probe_results: list) -> list:
        signals = []

        valid_results = [r for r in probe_results if not r.error and r.status_code > 0]
        if len(valid_results) < 2:
            return signals

        baseline_len  = len(baseline.body_snippet)
        baseline_time = baseline.response_time
        baseline_status = baseline.status_code

        body_lengths   = [len(r.body_snippet) for r in valid_results]
        response_times = [r.response_time for r in valid_results]
        status_codes   = [r.status_code for r in valid_results]

        # ── Body length delta ─────────────────────────────────────────────────
        if baseline_len > 0:
            avg_probe_len = sum(body_lengths) / len(body_lengths)
            delta_ratio   = abs(avg_probe_len - baseline_len) / max(baseline_len, 1)
            if delta_ratio > 0.4:   # body changed by >40% on average
                signals.append(DetectionSignal(
                    layer="behavioral",
                    signal_type="body_delta",
                    detail=f"Body length changed significantly vs baseline "
                           f"(baseline={baseline_len}B, avg probe={int(avg_probe_len)}B, "
                           f"delta={int(delta_ratio*100)}%)",
                    matched_waf=None,
                    confidence_contribution=20,
                ))

        # ── Response time spike ───────────────────────────────────────────────
        if baseline_time > 0 and response_times:
            avg_probe_time = sum(response_times) / len(response_times)
            time_ratio = avg_probe_time / baseline_time
            if time_ratio > 2.5:   # probes take 2.5x longer than baseline
                signals.append(DetectionSignal(
                    layer="behavioral",
                    signal_type="timing",
                    detail=f"Response time spike on probes "
                           f"(baseline={baseline_time}s, avg probe={avg_probe_time:.2f}s, "
                           f"ratio={time_ratio:.1f}x) — suggests deep inspection",
                    matched_waf=None,
                    confidence_contribution=20,
                ))

        # ── Block rate ────────────────────────────────────────────────────────
        block_count = sum(1 for s in status_codes if s in BLOCK_STATUS_CODES)
        block_rate  = block_count / len(valid_results)
        if block_rate >= 0.3:      # 30%+ of probes got blocked
            contrib = int(block_rate * 40)  # scales up to 40 pts
            signals.append(DetectionSignal(
                layer="behavioral",
                signal_type="block_rate",
                detail=f"{block_count}/{len(valid_results)} probes blocked "
                       f"({int(block_rate*100)}% block rate)",
                matched_waf=None,
                confidence_contribution=min(contrib, 40),
            ))

        # ── Status code variance ──────────────────────────────────────────────
        unique_codes = set(status_codes)
        if len(unique_codes) >= 3:
            signals.append(DetectionSignal(
                layer="behavioral",
                signal_type="status_variance",
                detail=f"High status code variance across probes: {sorted(unique_codes)} "
                       "— WAF differentiating request types",
                matched_waf=None,
                confidence_contribution=15,
            ))

        # ── Consistent size mismatch on blocked requests ──────────────────────
        blocked_sizes = [len(r.body_snippet) for r in valid_results
                         if r.status_code in BLOCK_STATUS_CODES]
        if len(blocked_sizes) >= 2:
            size_variance = max(blocked_sizes) - min(blocked_sizes)
            if size_variance < 50:   # blocked pages are near-identical → templated block page
                signals.append(DetectionSignal(
                    layer="behavioral",
                    signal_type="templated_block",
                    detail=f"Blocked responses have near-identical body sizes "
                           f"(range: {min(blocked_sizes)}-{max(blocked_sizes)}B) "
                           "— strong indicator of WAF block template",
                    matched_waf=None,
                    confidence_contribution=35,
                ))

        return signals


# ─────────────────────────────────────────────────────────────────────────────
# LAYER 4 — CONFIDENCE SCORING ENGINE
# ─────────────────────────────────────────────────────────────────────────────
class ConfidenceEngine:
    """
    Aggregates all signals into a final confidence score.

    Scoring rules:
      - Signals from multiple independent layers add more confidence than
        repeated signals from the same layer
      - Specific WAF name matches contribute more than generic signals
      - Score is capped at 100
      - Verdict bands:
          0-20  : No WAF detected
          21-40 : Possibly a WAF (low confidence)
          41-65 : WAF likely present
          66-85 : WAF detected (high confidence)
          86-100: WAF confirmed (very high confidence)
    """

    def compute(self, signals: list) -> tuple:
        """Returns (score: int, waf_names: list, verdict: str)"""
        if not signals:
            return 0, [], "No WAF detected"

        # Deduplicate: one signal type per layer per WAF (avoid score inflation)
        seen = set()
        deduped = []
        for s in signals:
            key = (s.layer, s.signal_type, s.matched_waf or "generic")
            if key not in seen:
                seen.add(key)
                deduped.append(s)

        # Layer diversity bonus: signals from 2+ layers add 10pt bonus each
        layers_present = {s.layer for s in deduped}
        layer_bonus    = max(0, (len(layers_present) - 1) * 10)

        raw_score = sum(s.confidence_contribution for s in deduped) + layer_bonus
        score     = min(100, raw_score)

        # Collect WAF names (de-duplicated, sorted by frequency)
        name_counts = {}
        for s in deduped:
            if s.matched_waf:
                name_counts[s.matched_waf] = name_counts.get(s.matched_waf, 0) + 1
        waf_names = sorted(name_counts, key=lambda k: -name_counts[k])

        # Verdict
        if score <= 20:
            verdict = "No WAF detected"
        elif score <= 40:
            verdict = "Possibly a WAF (low confidence) — manual inspection recommended"
        elif score <= 65:
            verdict = "WAF likely present"
        elif score <= 85:
            verdict = "WAF detected (high confidence)"
        else:
            verdict = "WAF confirmed (very high confidence)"

        return score, waf_names, verdict


